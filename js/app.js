function renderPlanTable(filter) {
  const tbody = document.getElementById('planTableBody');
  if (!tbody) return;
  const q = (filter || '').toLowerCase().trim();
  let html = '';
  let visible = 0;
  let currentSection = '';

  for (const row of PLAN_DATA) {
    if (row.section) {
      currentSection = row.section;
      continue;
    }
    const matchNum  = row.num.toLowerCase().includes(q);
    const matchName = row.name.toLowerCase().includes(q);
    const matchSub  = row.sub.toLowerCase().includes(q);
    if (q && !matchNum && !matchName && !matchSub) continue;
    if (!q || visible === 0 || currentSection !== html._lastSection) {
      html += `<tr class="section-row"><td colspan="3">${currentSection}</td></tr>`;
      html._lastSection = currentSection;
    }
    visible++;
    html += `<tr>
      <td><span class="account-num">${row.num}</span></td>
      <td>${row.name}</td>
      <td class="subaccounts">${row.sub || '—'}</td>
    </tr>`;
  }

  if (visible === 0) {
    html = `<tr><td colspan="3" style="text-align:center;padding:24px;color:var(--text-subtle)">Ничего не найдено</td></tr>`;
  }
  tbody.innerHTML = html;
}

function initPlanModal() {
  const input = document.getElementById('planSearch');
  if (input) {
    input.addEventListener('input', () => renderPlanTable(input.value));
  }
  const modal = document.getElementById('planModal');
  if (modal) {
    modal.addEventListener('show.bs.modal', () => renderPlanTable(''));
  }
}

